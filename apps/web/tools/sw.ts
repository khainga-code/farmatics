import type { Plugin } from 'vite';

/**
 * The app shell is cached by a service worker. Without a revision, a phone
 * that already installed the worker keeps the cache name it was born with and
 * can serve an old shell against new assets. The cache name here is derived
 * from the built filenames, which Vite hashes, so every deploy installs a new
 * worker and activation deletes the previous cache.
 */

/** FNV-1a: tiny, deterministic, and enough to name a cache. */
export function buildId(parts: readonly string[]): string {
  let hash = 0x811c9dc5;
  const source = [...parts].sort().join('\n');
  for (let index = 0; index < source.length; index += 1) {
    hash ^= source.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash.toString(16).padStart(8, '0');
}

/**
 * The shell and every hashed asset are cached up front. Older public files
 * keep their names, so they travel with the served shell.
 */
export function precacheEntries(assets: readonly string[]): string[] {
  const entries = ['/', '/index.html', '/manifest.webmanifest', '/icon.svg', '/favicon.svg'];
  for (const asset of [...assets].sort()) entries.push(`/${asset}`);
  return entries;
}

export function renderServiceWorker(options: {
  buildId: string;
  precache: readonly string[];
}): string {
  const cache = `farmatics-shell-${options.buildId}`;
  return `/*
 * Generated from apps/web/tools/sw.ts at build time. Do not edit this file.
 *
 * Network-first for navigation, so a deploy is picked up as soon as the phone
 * has signal; cache fallback, so the app still opens with none. API calls are
 * never cached - the sync engine and Dexie are the only source of farm data.
 */
var CACHE = ${JSON.stringify(cache)};
var PRECACHE = ${JSON.stringify(options.precache)};

self.addEventListener('install', function (event) {
  event.waitUntil(
    caches
      .open(CACHE)
      .then(function (cache) {
        return cache.addAll(PRECACHE);
      })
      .then(function () {
        return self.skipWaiting();
      }),
  );
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches
      .keys()
      .then(function (keys) {
        return Promise.all(
          keys
            .filter(function (key) {
              return key !== CACHE;
            })
            .map(function (key) {
              return caches.delete(key);
            }),
        );
      })
      .then(function () {
        return self.clients.claim();
      }),
  );
});

self.addEventListener('fetch', function (event) {
  var request = event.request;
  if (request.method !== 'GET') return;

  var url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.indexOf('/api/') === 0) return;

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then(function (response) {
          if (response.ok) {
            var copy = response.clone();
            void caches.open(CACHE).then(function (cache) {
              return cache.put('/index.html', copy);
            });
          }
          return response;
        })
        .catch(function () {
          return caches.match('/index.html').then(function (cached) {
            return cached || Response.error();
          });
        }),
    );
    return;
  }

  event.respondWith(
    caches.match(request).then(function (cached) {
      if (cached) return cached;
      return fetch(request).then(function (response) {
        if (response.ok) {
          var copy = response.clone();
          void caches.open(CACHE).then(function (cache) {
            return cache.put(request, copy);
          });
        }
        return response;
      });
    }),
  );
});
`;
}

export function serviceWorker(): Plugin {
  return {
    name: 'farmatics-service-worker',
    apply: 'build',
    generateBundle(_output, bundle) {
      const assets = Object.keys(bundle).filter((fileName) => fileName.startsWith('assets/'));
      const shell = bundle['index.html'];
      const shellSource = shell?.type === 'asset' ? String(shell.source) : '';
      const id = buildId([...assets, shellSource]);

      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: renderServiceWorker({ buildId: id, precache: precacheEntries(assets) }),
      });
    },
  };
}
